#!/usr/bin/env python3
"""Generate docs/CONTENT_CHECKLIST.md from every <mark class="ph" data-ph="..."> in the HTML
and from assets/js/main.js (footer placeholders). Run after every content change.

Usage: python3 tools/content_checklist.py
"""
import os, re, glob, html
from collections import OrderedDict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAT = re.compile(r'<mark class="ph" data-ph="([^"]+)">(.*?)</mark>', re.S)

found = OrderedDict()
sources = sorted(glob.glob(os.path.join(ROOT, "*.html"))) + [os.path.join(ROOT, "assets", "js", "main.js")]
for path in sources:
    name = os.path.basename(path)
    for pid, text in PAT.findall(open(path, encoding="utf-8").read()):
        text = html.unescape(re.sub(r"<[^>]+>", "", text)).strip()
        entry = found.setdefault(pid, {"text": text, "pages": []})
        if name not in entry["pages"]:
            entry["pages"].append(name)

# who answers: a light heuristic by id, to be corrected by hand in the sheet if wrong
def owner(pid):
    p = pid.lower()
    if any(k in p for k in ("capacity", "moq", "sample", "prodtime", "machines", "lines", "special", "inline", "aql", "meas", "metal", "cuttable", "fusing", "notcore", "sqm", "tenure", "e1", "e2", "e3", "e4", "e5", "firstorder", "subcon", "waste", "energy", "founder", "founded", "people", "years")):
        return "Production director"
    if any(k in p for k in ("audit", "sedex", "smeta", "oeko", "gots", "coc", "rsl", "insurance", "reg", "profilepdf")):
        return "Management"
    if any(k in p for k in ("uk", "mail", "tel", "addr", "ddp", "payment", "transit", "reply", "trading", "flight", "km", "formaction", "ukco")):
        return "Burkay (UK side)"
    return "To assign"

lines = ["# Content checklist — every placeholder on the site", "",
         "Generated by `tools/content_checklist.py` from the `data-ph` marks in the HTML. "
         "Fill the Value column as answers arrive, then replace the mark in the HTML (keep the `<mark>` tag until launch so the review bar still counts it; set `REVIEW_MODE = false` in `assets/js/main.js` at launch).", "",
         f"Total: {len(found)} distinct placeholders.", "",
         "| ID | Appears as | Pages | Who answers | Value (fill in) | Status |", "|---|---|---|---|---|---|"]
for pid, e in found.items():
    pages = ", ".join(p.replace(".html", "").replace("main.js", "footer") for p in e["pages"])
    lines.append(f"| `{pid}` | {e['text']} | {pages} | {owner(pid)} |  | open |")

lines += ["", "## Image and video slots", "", "See `docs/PHOTO_BRIEF.md` (generated from `tools/slots.json`)."]
open(os.path.join(ROOT, "docs", "CONTENT_CHECKLIST.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(f"{len(found)} placeholders -> docs/CONTENT_CHECKLIST.md")
